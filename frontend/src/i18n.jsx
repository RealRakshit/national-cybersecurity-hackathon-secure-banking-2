const LanguageContext = createContext(null);

const translateChallenge = (value, language) => {
  if (language !== 'hi' || !value) return value;

  const captchaMatch = value.match(/^What is (\d+) \+ (\d+)\?$/);
  if (captchaMatch) return `${captchaMatch[1]} + ${captchaMatch[2]} कितना है?`;

  if (value.includes('circle')) return 'दिए गए बॉक्स में एक साफ़ गोला बनाएं।';
  if (value.includes('zigzag')) return 'दिए गए बॉक्स में एक साफ़ ज़िगज़ैग रेखा बनाएं।';

  const localTestingMatch = value.match(/^Verification code sent\. For local testing, use: (.+)$/);
  if (localTestingMatch) return `वेरिफिकेशन कोड भेज दिया गया। लोकल टेस्टिंग के लिए उपयोग करें: ${localTestingMatch[1]}`;

  const staticKey = Object.keys(translations.en).find((key) => translations.en[key] === value);
  return (staticKey && translations.hi[staticKey]) || dynamicHindi.get(value) || value;
};

export const LanguageProvider = ({ children }) => {
  const [language, setLanguage] = useState(() => localStorage.getItem('language') || 'en');

  const value = useMemo(() => {
    const t = (key, values = {}) => {
      const template = translations[language][key] || translations.en[key] || key;
      return Object.entries(values).reduce(
        (text, [name, replacement]) => text.replace(`{${name}}`, replacement),
        template,
      );
    };

    const setAppLanguage = (nextLanguage) => {
      localStorage.setItem('language', nextLanguage);
      setLanguage(nextLanguage);
    };

    return {
      language,
      isHindi: language === 'hi',
      setLanguage: setAppLanguage,
      toggleLanguage: () => setAppLanguage(language === 'hi' ? 'en' : 'hi'),
      t,
      td: (value) => translateChallenge(value, language),
    };
  }, [language]);

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
